class AlertAcknowledgement(Base):
    """
    Alerts themselves are computed live from real data on every request
    (see src/api/services/alert_service.py) rather than stored -- this
    table only records that a specific, deterministically-keyed alert
    has been acknowledged, so it stops reappearing in the feed.
    """

    __tablename__ = "alert_acknowledgements"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)

    alert_key: Mapped[str] = mapped_column(String(255), unique=True, index=True)

    acknowledged_by: Mapped[str] = mapped_column(String(150), default="")

    acknowledged_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )


class PredictionLog(Base):
    __tablename__ = "prediction_logs"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)

    experiment_id: Mapped[int] = mapped_column(
        ForeignKey("experiments.id"), index=True
    )

    input_features: Mapped[dict] = mapped_column(JSONB)

    predicted_class: Mapped[str] = mapped_column(String(100))

    probabilities: Mapped[dict] = mapped_column(JSONB)

    shap_explanation: Mapped[list] = mapped_column(JSONB)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    experiment: Mapped["Experiment"] = relationship(back_populates="predictions")
